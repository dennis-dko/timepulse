// IsCurrency reports whether code, in capitals, is one a project can be charged in.
func IsCurrency(code string) bool {
	_, found := slices.BinarySearch(currencies, code)

	return found
}

// Currencies are the codes a project can be charged in, in order.
func Currencies() []string {
	return slices.Clone(currencies)
}
